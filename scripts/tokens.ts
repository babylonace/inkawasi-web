/**
 * Turns the design system's `design-system/tokens.json` into `src/styles/tokens.generated.css`.
 * The JSON is the only source of colours, spacing, radius, shadows and type scale: nobody edits
 * those values by hand. To update them, copy the new `tokens.json` from the design system and
 * build; `npm run tokens` runs before `dev`, `build` and the tests that need it.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

interface Token {
  name: string;
  value: string;
  usage?: string;
}

interface TokenGroup {
  tokens: Token[];
}

export interface DesignTokens {
  name: string;
  version: number;
  color: TokenGroup;
  spacing: TokenGroup;
  radius: TokenGroup;
  shadow: TokenGroup;
  fontSize: TokenGroup;
  fontWeight: TokenGroup;
  lineHeight: TokenGroup;
  letterSpacing: TokenGroup;
}

/** Groups emitted, in order. Typography styles and font families are left out: Astro's font API owns the families. */
const GROUPS = [
  'color',
  'spacing',
  'radius',
  'shadow',
  'fontSize',
  'fontWeight',
  'lineHeight',
  'letterSpacing',
] as const;

/** `{cream-100}` (a reference to another token) becomes `var(--cream-100)`. */
function cssValue(value: string, known: Set<string>): string {
  return value.replace(/\{([a-z0-9-]+)\}/g, (_, ref: string) => {
    if (!known.has(ref)) throw new Error(`tokens.json: unknown reference {${ref}}`);
    return `var(--${ref})`;
  });
}

export function tokensToCss(tokens: DesignTokens): string {
  const all = GROUPS.flatMap((group) => tokens[group].tokens);
  const known = new Set(all.map((t) => t.name));
  if (known.size !== all.length) throw new Error('tokens.json: duplicate token names');

  const lines = GROUPS.flatMap((group) => [
    `    /* ${group} */`,
    ...tokens[group].tokens.map((t) => `    --${t.name}: ${cssValue(t.value, known)};`),
  ]);
  return [
    `/* Generated by scripts/tokens.ts from design-system/tokens.json (${tokens.name} v${tokens.version}). Do not edit. */`,
    '@layer tokens {',
    '  :root {',
    ...lines,
    '  }',
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(await readFile('design-system/tokens.json', 'utf8')) as DesignTokens;
  await writeFile('src/styles/tokens.generated.css', tokensToCss(tokens));
  console.log('Wrote src/styles/tokens.generated.css');
}
